import json
import logging
import re
from typing import Any, Dict, List, Union

from cf2tf.terraform.hcl2.custom import LiteralType
from cf2tf.terraform.hcl2.primitive import PrimitiveTypes, StringType, TerraformType

log = logging.getLogger("cf2tf")

# An unquoted HCL2 object key has to be a valid identifier: it must start with
# a letter or underscore and may only contain letters, digits and underscores.
# CloudFormation map keys (for example IAM condition keys like ``ecs:cluster``)
# often contain characters such as ``:`` or ``-`` that are not allowed here.
VALID_IDENTIFIER = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

# References generated by cf2tf itself, e.g. ``aws_ecs_cluster.my_cluster.arn``
# or ``var.tag_key``. When such an expression is used as a map key it must be
# wrapped in parentheses to be parsed as a dynamic object key in HCL2.
TERRAFORM_REFERENCE = re.compile(
    r"^[A-Za-z_][A-Za-z0-9_]*(?:\.[A-Za-z_][A-Za-z0-9_]*|\[[0-9]+\])*$"
)


class ListType(list, TerraformType):
    def __init__(self, value: List[TerraformType]) -> None:
        """Default constructor

        Args:
            value (str): The value for this Terraform type.
        """
        super().__init__(value)
        self.value = value

    def __str__(self) -> str:
        return self.render()

    def render(self, indent=0):
        return render_tf_list(self, indent)


class MapType(dict, TerraformType):
    def __init__(self, value=Dict[PrimitiveTypes, TerraformType]) -> None:
        """Default constructor

        Args:
            value (str): The value for this Terraform type.
        """
        super().__init__(value)
        self.value = value

    def __str__(self) -> str:
        return self.render()

    def render(self, indent=0):
        return render_tf_map(self, indent)


ComplexTypes = Union[ListType, MapType]


def render_map_key(key: Union[PrimitiveTypes, LiteralType, str]) -> str:
    """Renders a map key using valid HCL2 object-key syntax.

    Bare identifiers are kept unquoted. Other static keys (arbitrary strings,
    numbers, booleans, ...) are emitted as double-quoted strings with JSON
    style escaping so that illegal identifier characters cannot produce an
    invalid HCL file. Terraform expression keys (only produced by cf2tf for
    dynamic resource tags) are wrapped in parentheses so their meaning as an
    expression is preserved.

    Args:
        key (PrimitiveTypes | LiteralType | str): The raw key of a map item.

    Returns:
        str: The rendered key, valid on the left side of ``=`` in an object.
    """
    if isinstance(key, StringType):
        return key.render()

    if isinstance(key, LiteralType):
        expression = key.render(0)

        if VALID_IDENTIFIER.match(expression):
            return expression

        if TERRAFORM_REFERENCE.match(expression):
            return f"({expression})"

        return json.dumps(expression, ensure_ascii=False)

    if isinstance(key, str):
        if VALID_IDENTIFIER.match(key):
            return key

        return json.dumps(key, ensure_ascii=False)

    # NumberType, BooleanType and NullType keys are rare but render safely.
    return json.dumps(str(key), ensure_ascii=False)


def render_tf_list(items: List[TerraformType], indent=0):
    rear_brace = " " * indent

    indent += 2

    spacing = " " * indent

    result = "[\n"

    for item in items:
        comma = "" if item is items[-1] else ","

        result += f"{spacing}{item.render(indent)}{comma}\n"

    result += f"{rear_brace}]"

    return result


def render_tf_map(items: Dict[Any, TerraformType], indent=0):
    rear_brace = " " * indent

    indent += 2

    spacing = " " * indent

    result = "{"

    for name, value in items.items():
        result = result + f"\n{spacing}{render_map_key(name)} = {value.render(indent)}"

    return result + f"\n{rear_brace}}}"
